async function runWorkflowCode(jsCode, input) {
  const wrapped = `(async () => { const $json = ${JSON.stringify(input)}; ${jsCode} })()`
  const context = vm.createContext({
    AbortController,
    Boolean,
    console,
    fetch,
    Number,
    Set,
    String,
    TextDecoder,
    URL,
  })

  return vm.runInContext(wrapped, context, { timeout: 15000 })
}

function titleize(value) {
  return String(value || '-')
    .replace(/[_-]/g, ' ')
    .replace(/\b\w/g, (letter) => letter.toUpperCase())
}

function isoDate(offsetDays = 0) {
  const date = new Date()
  date.setUTCDate(date.getUTCDate() + offsetDays)
  return date.toISOString().slice(0, 10)
}

