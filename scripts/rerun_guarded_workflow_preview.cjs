function serializeModule(data) {
  return `const vipPreviewData = ${JSON.stringify(data, null, 2)} as const\n\nexport default vipPreviewData\n`
}

runWorkflowCode(match[1], workflowInput)
  .then((result) => {
    const workflowResult = result?.json
    if (!workflowResult) throw new Error('Workflow did not return a json payload.')

    fs.mkdirSync(path.dirname(outputPath), { recursive: true })
    fs.writeFileSync(outputPath, serializeModule(buildPreviewData(workflowResult)))

    console.log(`Reran ${workflowResult.workflow_name}`)
    console.log(`Generated ${path.relative(repoRoot, outputPath)}`)
    console.log(`Engines run: ${workflowResult.engines_run.map(titleize).join(', ')}`)
  })
  .catch((error) => {
    console.error(error)
    process.exit(1)
  })
